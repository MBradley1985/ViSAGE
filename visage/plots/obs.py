    """Black hole and spheroid masses (M_sun) with errors, and `core`."""
    k = (0.7 / h) ** 2
    arr = lambda s, unit: k * unit * np.array(s.split(), float)  # noqa: E731
    return {
        "bh": arr(_BH, 1e8),
        "bh_hi": arr(_BH_HI, 1e8),
        "bh_lo": arr(_BH_LO, 1e8),
        "sph": arr(_SPH, 1e10),
        "sph_hi": arr(_SPH_HI, 1e10),
        "sph_lo": arr(_SPH_LO, 1e10),
        "core": np.array(_CORE.split(), int) == 1,
    }


